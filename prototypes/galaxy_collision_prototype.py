def enclosed_mass(core_mass, ring_masses, ring_radii, r):
    """Approximate mass enclosed within radius r, treating each ring as a
    thin shell (standard toy-model approximation: exact for a spherical
    shell, only approximate for an in-plane ring, but adequate for
    seeding a reasonable, flat-ish rotation curve). Vectorized over r,
    which may be a scalar or a numpy array."""
    r = np.asarray(r, dtype=np.float64)
    m = np.full_like(r, core_mass, dtype=np.float64)
    for mr, rr in zip(ring_masses, ring_radii):
        m = m + np.where(r >= rr, mr, 0.0)
    return m


def build_galaxy(seed, total_mass, disk_radius, thickness, center, bulk_vel, spin_dir, spiral_hand):
    """Builds the macro-particle skeleton + tracer stars for one galaxy.
    Returns dicts of numpy arrays ready to upload to Taichi fields.
    spin_dir = +1 or -1 (sense of disk rotation, about +z)
    spiral_hand = +1 or -1 (winding sense of the seeded spiral pattern)
    """
    rng = np.random.default_rng(seed)

    # ---- macro skeleton: core + concentric rings of point masses ----
    core_mass = total_mass * CORE_MASS_FRAC
    ring_masses_total = total_mass * RING_MASS_FRAC
    ring_radii = RING_RADIUS_FRAC * disk_radius

    macro_p = [np.array([0.0, 0.0, 0.0])]
    macro_v = [np.array([0.0, 0.0, 0.0])]
    macro_m = [core_mass]

    for ring_mass_total, rr in zip(ring_masses_total, ring_radii):
        m_each = ring_mass_total / MACROS_PER_RING
        v_circ = np.sqrt(G_SIM * enclosed_mass(core_mass, ring_masses_total, ring_radii, rr)
                          / (rr + SOFTENING))
        for k in range(MACROS_PER_RING):
            theta = 2.0 * np.pi * k / MACROS_PER_RING
            p = np.array([rr * np.cos(theta), rr * np.sin(theta), 0.0])
            tangential = np.array([-np.sin(theta), np.cos(theta), 0.0]) * spin_dir
            v = tangential * v_circ
            macro_p.append(p)
            macro_v.append(v)
            macro_m.append(m_each)

    macro_p = np.array(macro_p) + center
    macro_v = np.array(macro_v) + bulk_vel
    macro_m = np.array(macro_m)

    # ---- tracer stars ----
    n = N_STARS_PER_GALAXY
    n_bulge = int(n * BULGE_FRACTION)
    n_disk = n - n_bulge

    pos = np.zeros((n, 3))
    vel = np.zeros((n, 3))
    color = np.zeros((n, 3))
    bright = np.zeros(n)

    # -- disk population, seeded along a 2-arm logarithmic spiral --
    # exponential surface-density profile: more stars at small radius
    u = rng.random(n_disk)
    scale_len = disk_radius * 0.32
    r = -scale_len * np.log(1.0 - u * (1.0 - np.exp(-disk_radius / scale_len)))
    r = np.clip(r, 0.05, disk_radius)

    pitch = np.deg2rad(14.0)  # spiral pitch angle: tighter winding = smaller angle
    r0 = disk_radius * 0.12
    spiral_theta = spiral_hand * np.log(np.maximum(r, r0) / r0) / np.tan(pitch)

    arm_choice = rng.integers(0, 2, n_disk)              # which of the 2 arms
    on_arm = rng.random(n_disk) < 0.72                    # 72% clustered on arms, rest diffuse disk
    theta_random = rng.uniform(0, 2 * np.pi, n_disk)
    theta_arm = arm_choice * np.pi + spiral_theta + rng.normal(0, 0.28, n_disk)
    theta = np.where(on_arm, theta_arm, theta_random)

    z = rng.laplace(0.0, thickness * 0.5, n_disk)  # thin exponential-ish vertical profile

    x = r * np.cos(theta)
    y = r * np.sin(theta)

    v_circ = np.sqrt(G_SIM * enclosed_mass(core_mass, ring_masses_total, ring_radii, r)
                      / (r + SOFTENING))
    dispersion = 0.06  # velocity "temperature" of the disk, as a fraction of v_circ
    vx = -np.sin(theta) * v_circ * spin_dir + rng.normal(0, 1, n_disk) * v_circ * dispersion
    vy = np.cos(theta) * v_circ * spin_dir + rng.normal(0, 1, n_disk) * v_circ * dispersion
    vz = rng.normal(0, 1, n_disk) * v_circ * dispersion * 0.4

    pos[:n_disk] = np.stack([x, y, z], axis=1)
    vel[:n_disk] = np.stack([vx, vy, vz], axis=1)

    # color: cooler/younger (bluer) in the outer arms, warmer toward the core,
    # plus small per-star random hue jitter so the field doesn't look flat
    radial_frac = np.clip(r / disk_radius, 0.0, 1.0)
    bright[:n_disk] = np.clip(1.35 * np.exp(-r / (scale_len * 1.3)), 0.18, 1.5) * rng.uniform(0.6, 1.3, n_disk)

    # -- bulge population: puffy spheroid around the core --
    br = rng.exponential(disk_radius * 0.055, n_bulge)
    br = np.clip(br, 0.02, disk_radius * 0.28)
    bth = rng.uniform(0, 2 * np.pi, n_bulge)
    bph = np.arccos(rng.uniform(-1, 1, n_bulge))
    bx = br * np.sin(bph) * np.cos(bth)
    by = br * np.sin(bph) * np.sin(bth)
    bz = br * np.cos(bph) * 0.6

    v_circ_b = np.sqrt(G_SIM * enclosed_mass(core_mass, ring_masses_total, ring_radii, br)
                        / (br + SOFTENING))
    # bulge kinematics are hotter / more isotropic (pressure-supported, not cold-rotation-supported)
    bvx = -np.sin(bth) * v_circ_b * spin_dir * 0.5 + rng.normal(0, 1, n_bulge) * v_circ_b * 0.5
    bvy = np.cos(bth) * v_circ_b * spin_dir * 0.5 + rng.normal(0, 1, n_bulge) * v_circ_b * 0.5
    bvz = rng.normal(0, 1, n_bulge) * v_circ_b * 0.4

    pos[n_disk:] = np.stack([bx, by, bz], axis=1)
    vel[n_disk:] = np.stack([bvx, bvy, bvz], axis=1)
    bright[n_disk:] = np.clip(1.6 * np.exp(-br / (disk_radius * 0.08)), 0.5, 2.0) * rng.uniform(0.8, 1.2, n_bulge)

    pos += center
    vel += bulk_vel

    return {
        "macro_pos": macro_p, "macro_vel": macro_v, "macro_mass": macro_m,
        "star_pos": pos, "star_vel": vel, "bright": bright,
        "n_disk": n_disk, "radial_frac_disk": radial_frac,
    }


def make_colors(n, n_disk, radial_frac_disk, hue_rgb_inner, hue_rgb_outer, rng):
    """Blend an inner (bulge/old population) hue into an outer (young arm) hue."""
    color = np.zeros((n, 3))
    t_disk = radial_frac_disk[:, None]
    color[:n_disk] = hue_rgb_inner * (1 - t_disk) + hue_rgb_outer * t_disk
    color[n_disk:] = hue_rgb_inner * 1.05
    color += rng.uniform(-0.03, 0.03, color.shape)
    return np.clip(color, 0.0, 1.5)


def build_initial_conditions():
    """Sets up the full flyby -> tidal interaction -> merger encounter."""
    rng = np.random.default_rng(1234)

    sep = INITIAL_SEPARATION
    b = IMPACT_PARAMETER
    # place galaxies symmetric about the origin so the camera default framing works well
    half_sep = sep / 2.0
    center_a = np.array([-half_sep, -b / 2.0, 0.0])
    center_b = np.array([half_sep, b / 2.0, 0.0])

    # closing velocity along the line of approach, plus a small transverse
    # component from the impact parameter to give the encounter real orbital
    # angular momentum (this is what turns a head-on hit into a grazing,
    # tail-producing pass instead)
    approach_dir = (center_b - center_a)
    approach_dir = approach_dir / np.linalg.norm(approach_dir)
    transverse_dir = np.array([-approach_dir[1], approach_dir[0], 0.0])
    # v_rel = velocity of A relative to B: points mostly from A toward B (closing
    # the gap) plus a transverse component (from the impact parameter) that gives
    # the encounter real orbital angular momentum -- this is what turns a head-on
    # hit into a grazing, tail-producing pass instead.
    v_rel = approach_dir * INFALL_SPEED + transverse_dir * INFALL_SPEED * 0.22

    # split so total system momentum is ~zero (galaxies fall toward a common
    # barycenter rather than one being artificially held "stationary")
    mtot = MASS_A + MASS_B
    vel_a = v_rel * (MASS_B / mtot)
    vel_b = -v_rel * (MASS_A / mtot)

    gal_a = build_galaxy(1, MASS_A, DISK_RADIUS_A, DISK_THICKNESS_A, center_a, vel_a, spin_dir=1, spiral_hand=1)
    gal_b = build_galaxy(2, MASS_B, DISK_RADIUS_B, DISK_THICKNESS_B, center_b, vel_b, spin_dir=-1, spiral_hand=-1)

    milkyway_inner = np.array([1.15, 0.85, 0.55])   # warm bulge core
    milkyway_outer = np.array([0.55, 0.72, 1.05])   # cool blue-white arms
    andromeda_inner = np.array([1.2, 0.65, 0.45])   # warm amber core
    andromeda_outer = np.array([1.05, 0.75, 0.42])  # gold arms

    color_a = make_colors(N_STARS_PER_GALAXY, gal_a["n_disk"], gal_a["radial_frac_disk"],
                           milkyway_inner, milkyway_outer, rng)
    color_b = make_colors(N_STARS_PER_GALAXY, gal_b["n_disk"], gal_b["radial_frac_disk"],
                           andromeda_inner, andromeda_outer, rng)

    macro_p = np.concatenate([gal_a["macro_pos"], gal_b["macro_pos"]], axis=0)
    macro_v = np.concatenate([gal_a["macro_vel"], gal_b["macro_vel"]], axis=0)
    macro_m = np.concatenate([gal_a["macro_mass"], gal_b["macro_mass"]], axis=0)
    macro_g = np.concatenate([np.zeros(N_MACRO_PER_GALAXY), np.ones(N_MACRO_PER_GALAXY)]).astype(np.int32)

    star_p = np.zeros((N_STARS, 3), dtype=np.float32)
    star_v = np.zeros((N_STARS, 3), dtype=np.float32)
    star_c = np.zeros((N_STARS, 3), dtype=np.float32)
    star_b = np.zeros(N_STARS, dtype=np.float32)
    star_a = np.zeros(N_STARS, dtype=np.int32)

    a0, a1 = 0, N_STARS_PER_GALAXY
    b0, b1 = a1, a1 + N_STARS_PER_GALAXY
    star_p[a0:a1] = gal_a["star_pos"]
    star_v[a0:a1] = gal_a["star_vel"]
    star_c[a0:a1] = color_a
    star_b[a0:a1] = gal_a["bright"]
    star_a[a0:a1] = 1

    star_p[b0:b1] = gal_b["star_pos"]
    star_v[b0:b1] = gal_b["star_vel"]
    star_c[b0:b1] = color_b
    star_b[b0:b1] = gal_b["bright"]
    star_a[b0:b1] = 1

    # user-spawn pool: parked at the origin, invisible (brightness 0) until fired
    star_c[b1:] = np.array([1.0, 1.0, 1.0])

    return {
        "macro_p": macro_p.astype(np.float32), "macro_v": macro_v.astype(np.float32),
        "macro_m": macro_m.astype(np.float32), "macro_g": macro_g,
        "star_p": star_p, "star_v": star_v, "star_c": star_c, "star_b": star_b, "star_a": star_a,
    }


def upload_initial_conditions():
    ic = build_initial_conditions()
    macro_pos.from_numpy(ic["macro_p"])
    macro_vel.from_numpy(ic["macro_v"])
    macro_mass.from_numpy(ic["macro_m"])
    macro_gal.from_numpy(ic["macro_g"])

    star_pos.from_numpy(ic["star_p"])
    star_vel.from_numpy(ic["star_v"])
    star_base_color.from_numpy(ic["star_c"])
    star_brightness.from_numpy(ic["star_b"])
    star_active.from_numpy(ic["star_a"])

    twinkle = np.random.default_rng(7).uniform(0, 2 * np.pi, N_STARS).astype(np.float32)
    star_twinkle_phase.from_numpy(twinkle)

    sim_time[None] = 0.0
    next_pool_slot[None] = 0
    trail_head[0] = 0
    trail_head[1] = 0
    trail_count[0] = 0
    trail_count[1] = 0


def build_grid():
    verts = np.zeros((GRID_LINES * 4, 3), dtype=np.float32)
    coords = np.linspace(-GRID_EXTENT, GRID_EXTENT, GRID_LINES)
    idx = 0
    for c in coords:
        verts[idx] = [c, -GRID_EXTENT, 0.0]; idx += 1
        verts[idx] = [c, GRID_EXTENT, 0.0]; idx += 1
        verts[idx] = [-GRID_EXTENT, c, 0.0]; idx += 1
        verts[idx] = [GRID_EXTENT, c, 0.0]; idx += 1
    grid_verts.from_numpy(verts)


