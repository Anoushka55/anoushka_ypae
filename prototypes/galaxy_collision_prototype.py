# Softening length: real stars have zero radius, but our "stars" are tracer
# particles standing in for huge (~10^6-10^8 solar mass) clumps of real
# stars, and our "macro masses" stand in for whole mass concentrations.
# Without softening, a close pass between two point masses gives an
# unphysical infinite-force slingshot. SOFTENING sets the distance below
# which gravity is smoothly capped, mimicking the finite size of a real
# bulge/disk mass concentration.
