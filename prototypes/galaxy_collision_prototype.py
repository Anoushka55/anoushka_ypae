@ti.func
def softened_accel(pos_from, pos_to, mass_to):
    """Newtonian acceleration on a body at pos_from due to a mass at pos_to,
    with Plummer-style softening: a = G*m*r_vec / (r^2 + eps^2)^1.5"""
    d = pos_to - pos_from
    r2 = d.dot(d) + SOFTENING2
    inv_r3 = 1.0 / (r2 * ti.sqrt(r2))
    return d * (G_SIM * mass_to * inv_r3)


@ti.kernel
def compute_galaxy_com():
    for g in range(2):
        gal_com_pos[g] = ti.Vector([0.0, 0.0, 0.0])
        gal_com_vel[g] = ti.Vector([0.0, 0.0, 0.0])
        gal_com_mass[g] = 0.0
    for i in range(N_MACRO):
        g = macro_gal[i]
        m = macro_mass[i]
        gal_com_pos[g] += macro_pos[i] * m
        gal_com_vel[g] += macro_vel[i] * m
        gal_com_mass[g] += m
    for g in range(2):
        gal_com_pos[g] /= gal_com_mass[g]
        gal_com_vel[g] /= gal_com_mass[g]


@ti.kernel
def compute_macro_accel():
    for i in range(N_MACRO):
        acc = ti.Vector([0.0, 0.0, 0.0])
        for j in range(N_MACRO):
            if j != i:
                acc += softened_accel(macro_pos[i], macro_pos[j], macro_mass[j])
        macro_acc[i] = acc

    # --- simplified Chandrasekhar dynamical friction between the two galaxies ---
    # Represents drag from each galaxy plowing through the other's extended
    # (unmodeled) dark-matter halo; strength falls off with separation via an
    # assumed isothermal-like halo density profile ~ 1/(r^2 + core^2), and
    # is applied as a uniform deceleration of each galaxy's bulk motion
    # relative to the other, with masses balanced so total momentum is conserved.
    sep_vec = gal_com_pos[1] - gal_com_pos[0]
    sep2 = sep_vec.dot(sep_vec) + SOFTENING2
    v_rel = gal_com_vel[1] - gal_com_vel[0]
    v_rel_mag = ti.sqrt(v_rel.dot(v_rel)) + VELOCITY_SOFTENING
    halo_falloff = 1.0 / (sep2 + DYN_FRICTION_CORE_RADIUS * DYN_FRICTION_CORE_RADIUS)
    drag_accel_mag = DYN_FRICTION_COEFF * halo_falloff
    drag_dir = v_rel / v_rel_mag
    # deceleration applied to galaxy 1 (relative motion), reaction on galaxy 0
    # scaled by mass ratio so net momentum change stays ~0
    accel_on_1 = -drag_dir * drag_accel_mag
    accel_on_0 = -accel_on_1 * (gal_com_mass[1] / gal_com_mass[0])
    for i in range(N_MACRO):
        if macro_gal[i] == 0:
            macro_acc[i] += accel_on_0
        else:
            macro_acc[i] += accel_on_1


@ti.kernel
def kick_macro(dt: ti.f32):
    for i in range(N_MACRO):
        macro_vel[i] += 0.5 * dt * macro_acc[i]


@ti.kernel
def drift_macro(dt: ti.f32):
    for i in range(N_MACRO):
        macro_pos[i] += dt * macro_vel[i]


@ti.kernel
def compute_star_accel():
    for s in range(N_STARS):
        acc = ti.Vector([0.0, 0.0, 0.0])
        p = star_pos[s]
        for j in range(N_MACRO):
            acc += softened_accel(p, macro_pos[j], macro_mass[j])
        star_acc[s] = acc


@ti.kernel
def kick_stars(dt: ti.f32):
    for s in range(N_STARS):
        star_vel[s] += 0.5 * dt * star_acc[s] * star_active[s]


@ti.kernel
def drift_stars(dt: ti.f32):
    for s in range(N_STARS):
        star_pos[s] += dt * star_vel[s] * star_active[s]


@ti.kernel
def recycle_escaped_stars():
    barycenter = (gal_com_pos[0] * gal_com_mass[0] + gal_com_pos[1] * gal_com_mass[1]) \
                 / (gal_com_mass[0] + gal_com_mass[1])
    for s in range(N_STARS):
        if star_active[s] == 1:
            d = star_pos[s] - barycenter
            if d.dot(d) > ESCAPE_RADIUS * ESCAPE_RADIUS:
                # respawn into whichever galaxy remnant is nearer, on a fresh
                # circular-ish orbit, so the disks stay visually full forever
                nearer = 0
                d0 = star_pos[s] - gal_com_pos[0]
                d1 = star_pos[s] - gal_com_pos[1]
                if d0.dot(d0) > d1.dot(d1):
                    nearer = 1
                rad = ti.sqrt(ti.random()) * 8.0 + 0.5
                theta = ti.random() * 6.2831853
                z = (ti.random() - 0.5) * 0.4
                local = ti.Vector([rad * ti.cos(theta), rad * ti.sin(theta), z])
                v_circ = ti.sqrt(G_SIM * gal_com_mass[nearer] / (rad + SOFTENING)) * 0.7
                tangential = ti.Vector([-ti.sin(theta), ti.cos(theta), 0.0])
                star_pos[s] = gal_com_pos[nearer] + local
                star_vel[s] = gal_com_vel[nearer] + tangential * v_circ


@ti.kernel
def update_render_colors(t: ti.f32):
    for s in range(N_STARS):
        twinkle = 1.0 + 0.06 * ti.sin(t * 2.3 + star_twinkle_phase[s])
        b = star_brightness[s] * twinkle * star_active[s]
        star_render_color[s] = star_base_color[s] * b


@ti.kernel
def push_trail(g: ti.i32, pos: ti.types.vector(3, ti.f32)):
    h = trail_head[g]
    trail_pos[g, h] = pos
    trail_head[g] = (h + 1) % TRAIL_LEN
    if trail_count[g] < TRAIL_LEN:
        trail_count[g] += 1


def _make_build_trail_segments(g):
    segs = trail_segments[g]
    cols = trail_seg_color[g]
    base_color = ti.Vector([0.9, 0.75, 0.35]) if g == 0 else ti.Vector([0.4, 0.75, 1.0])

    @ti.kernel
    def build():
        cnt = trail_count[g]
        for k in range(TRAIL_LEN - 1):
            if k < cnt - 1:
                i0 = (trail_head[g] - 1 - k) % TRAIL_LEN
                i1 = (trail_head[g] - 2 - k) % TRAIL_LEN
                if i0 < 0:
                    i0 += TRAIL_LEN
                if i1 < 0:
                    i1 += TRAIL_LEN
                segs[2 * k] = trail_pos[g, i0]
                segs[2 * k + 1] = trail_pos[g, i1]
                fade = 1.0 - k / ti.cast(TRAIL_LEN, ti.f32)
                cols[2 * k] = base_color * fade
                cols[2 * k + 1] = base_color * fade
            else:
                segs[2 * k] = trail_pos[g, trail_head[g]]
                segs[2 * k + 1] = trail_pos[g, trail_head[g]]
                cols[2 * k] = ti.Vector([0.0, 0.0, 0.0])
                cols[2 * k + 1] = ti.Vector([0.0, 0.0, 0.0])

    return build


build_trail_segments_0 = _make_build_trail_segments(0)
build_trail_segments_1 = _make_build_trail_segments(1)


@ti.kernel
def update_core_glow():
    core_glow_pos[0] = macro_pos[0]
    core_glow_pos[1] = macro_pos[N_MACRO_PER_GALAXY]
    # brighten the nucleus glow with how tightly the two cores have merged,
    # so the remnant's single nucleus reads as more luminous post-merger
    sep = macro_pos[0] - macro_pos[N_MACRO_PER_GALAXY]
    d = ti.sqrt(sep.dot(sep))
    boost = 1.0 + 1.5 / (1.0 + d * 0.15)
    core_glow_color[0] = ti.Vector([1.0, 0.85, 0.55]) * boost
    core_glow_color[1] = ti.Vector([1.0, 0.7, 0.45]) * boost


@ti.kernel
def spawn_probe_burst(cx: ti.f32, cy: ti.f32, cz: ti.f32, start_idx: ti.i32, count: ti.i32):
    for k in range(count):
        idx = (start_idx + k) % N_USER_POOL + 2 * N_STARS_PER_GALAXY
        r = ti.random() * 1.5
        theta = ti.random() * 6.2831853
        star_pos[idx] = ti.Vector([cx + r * ti.cos(theta), cy + r * ti.sin(theta), cz + (ti.random() - 0.5) * 0.5])
        speed = 0.05 + ti.random() * 0.08
        vth = ti.random() * 6.2831853
        star_vel[idx] = ti.Vector([speed * ti.cos(vth), speed * ti.sin(vth), (ti.random() - 0.5) * 0.03])
        star_brightness[idx] = 1.8
        star_active[idx] = 1


