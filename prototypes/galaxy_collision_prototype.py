# 8. MAIN LOOP: window, scene, UI, controls
# =========================================================================
def main():
    print(__doc__)

    build_grid()
    upload_initial_conditions()

    window = ti.ui.Window("Milky Way - Andromeda Collision Laboratory", (1280, 800), vsync=True)
    canvas = window.get_canvas()
    scene = window.get_scene()
    camera = ti.ui.Camera()
    orbit = OrbitCamera()

    paused = False
    time_scale = 1.0
    show_grid = True
    show_trails = True
    frame_count = 0
    trail_stride = 6   # only push a trail point every few frames (keeps history long in sim-time)

    print(f"Bodies: {N_MACRO} gravity-skeleton masses driving {N_STARS} tracer stars.")
    print("Window open. Controls are listed above; have fun flying around the collision.")

    while window.running:
        for e in window.get_events(ti.ui.PRESS):
            if e.key == ti.ui.ESCAPE:
                window.running = False
            elif e.key == ti.ui.SPACE:
                paused = not paused
            elif e.key == 'r':
                upload_initial_conditions()
                orbit.__init__()
                time_scale = 1.0
            elif e.key in (']', ti.ui.UP):
                time_scale = float(np.clip(time_scale * 1.4, MIN_TIME_SCALE, MAX_TIME_SCALE))
            elif e.key in ('[', ti.ui.DOWN):
                time_scale = float(np.clip(time_scale / 1.4, MIN_TIME_SCALE, MAX_TIME_SCALE))
            elif e.key == 'g':
                show_grid = not show_grid
            elif e.key == 't':
                show_trails = not show_trails
            elif e.key == ti.ui.LMB and window.is_pressed(ti.ui.SHIFT):
                mx, my = window.get_cursor_pos()
                ndc_x = (mx - 0.5) * 2.0
                ndc_y = (my - 0.5) * 2.0
                eye = orbit.eye()
                right, up = orbit.basis()
                forward = (orbit.target - eye)
                forward = forward / (np.linalg.norm(forward) + 1e-9)
                fov_scale = np.tan(np.deg2rad(45.0 / 2.0))
                aspect = 1280.0 / 800.0
                ray_dir = forward + right * (ndc_x * fov_scale * aspect) + up * (ndc_y * fov_scale)
                ray_dir = ray_dir / (np.linalg.norm(ray_dir) + 1e-9)
                if abs(ray_dir[2]) > 1e-6:
                    tpar = -eye[2] / ray_dir[2]
                    if tpar > 0:
                        hit = eye + ray_dir * tpar
                        start = int(next_pool_slot[None])
                        spawn_probe_burst(float(hit[0]), float(hit[1]), 0.0, start, 60)
                        next_pool_slot[None] = (start + 60) % N_USER_POOL

        orbit.handle_input(window)

        if not paused:
            steps = int(np.clip(round(STEPS_PER_FRAME_BASE * time_scale), 1, MAX_STEPS_PER_FRAME))
            for _ in range(steps):
                physics_step(DT_BASE)
            frame_count += 1
            if frame_count % trail_stride == 0:
                push_trail(0, gal_com_pos[0])
                push_trail(1, gal_com_pos[1])
            if os.environ.get("SIM_DEBUG") and frame_count % 30 == 0:
                com_np = gal_com_pos.to_numpy()
                sep = com_np[0] - com_np[1]
                print(f"[debug] t={sim_time[None]:7.2f}  separation={np.linalg.norm(sep):7.2f} kpc", flush=True)

        update_render_colors(sim_time[None])

        camera.position(*orbit.eye())
        camera.lookat(*orbit.target)
        camera.up(0.0, 0.0, 1.0)
        camera.fov(45.0)
        scene.set_camera(camera)
        scene.ambient_light((0.75, 0.75, 0.8))
        scene.point_light(pos=(60.0, 60.0, 90.0), color=(0.5, 0.5, 0.55))

        if show_grid:
            scene.lines(grid_verts, color=(0.12, 0.16, 0.22), width=1.0)

        if show_trails:
            build_trail_segments_0()
            build_trail_segments_1()
            scene.lines(trail_segments[0], per_vertex_color=trail_seg_color[0], width=2.0)
            scene.lines(trail_segments[1], per_vertex_color=trail_seg_color[1], width=2.0)

        scene.particles(star_pos, radius=0.09, per_vertex_color=star_render_color)

        # bright galactic-nucleus glow markers (the two dense cores)
        update_core_glow()
        scene.particles(core_glow_pos, radius=0.55, per_vertex_color=core_glow_color)

        canvas.set_background_color((0.01, 0.01, 0.02))
        canvas.scene(scene)

        gui = window.get_gui()
        with gui.sub_window("Simulation", 0.01, 0.01, 0.30, 0.16) as w:
            w.text(f"t = {sim_time[None]:.2f} units  (~{sim_time[None]*MYR_PER_TIME_UNIT:.0f} Myr)")
            w.text(f"time scale: {time_scale:.2f}x   {'PAUSED' if paused else 'running'}")
            w.text(f"stars: {N_STARS}   skeleton masses: {N_MACRO}")
            w.text("SPACE pause | R reset | ]/[ speed | Shift+Click spawn")

        window.show()


if __name__ == "__main__":
    main()
