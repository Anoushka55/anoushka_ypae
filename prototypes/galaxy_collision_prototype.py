"""
MILKY WAY <-> ANDROMEDA: an interactive galaxy-collision laboratory
=====================================================================

Run with:  uv run --python 3.12 --with taichi sim.py

PHYSICAL MODEL (read this before touching constants)
------------------------------------------------------------------------
Simulating tens of thousands of stars with true pairwise (star-to-star)
gravity is O(N^2) and is exactly the "computationally unrealistic
brute-force" approach we were told to avoid -- on integrated laptop
graphics it would crawl at a few frames per *minute*, not per second.

Instead we use the classic technique that was actually used to *discover*
tidal tails and bridges (Toomre & Toomre, 1972, "Galactic Bridges and
Tails"), extended with a small multipole expansion instead of a single
point mass per galaxy:

    * Each galaxy's gravity field is generated by a small "macro-particle
      skeleton": one dense central mass (bulge/core) plus a handful of
      ring masses that trace the disk's mass profile. There are only
      N_MACRO (~50) of these, so they can be evolved with an *exact*
      pairwise N-body sum (50^2 = 2500 pair checks -- trivial).
    * Thousands of individual stars are massless "test particles" that
      feel gravity FROM the macro-skeleton (an O(N_stars * N_macro) sum,
      fully data-parallel, and cheap: ~50 force evaluations per star)
      but do not pull on each other or on the skeleton. This is exactly
      how real restricted N-body galaxy-merger movies are made, and it
      is why stars never "collide": they only ever respond to the smooth
      large-scale field, never to one another.

This is a reduced-order approximation of full self-gravitating N-body
dynamics (real disks are also stabilized/perturbed by their own
star-star self-gravity, which we do not model star-by-star). It still
reproduces the real, famous phenomena: differential rotation winding up
a seeded spiral pattern, tidal stretching of the encounter into long
stellar streams, a close flyby, a fall-back, and -- thanks to a small
dynamical-friction drag standing in for the drag of the extended dark
matter halos (Chandrasekhar 1943) -- an eventual merger into one remnant.

UNITS
------------------------------------------------------------------------
Galaxy-scale dynamics does not fit comfortably into AU / solar mass /
year (numbers become >10^9), so -- keeping the *spirit* of "pick units
where G is a simple constant and numbers stay near order-1" -- we use
standard galactic N-body units instead:

    length unit   L0 = 1 kpc
    mass unit     M0 = 1e11 solar masses
    G_SIM         = 1.0   (by construction of the unit system below)

Given the real gravitational constant G_real = 4.30091e-6 kpc*(km/s)^2 /
Msun, setting G_SIM = 1 fixes the remaining units:
    velocity unit V0 = sqrt(G_real * M0 / L0) = 655.8 km/s
    time unit     T0 = L0 / V0               = 1.49 Myr
So "10 time units" of simulation is about 15 Myr of real time, and a
star drifting at "1" is moving at ~656 km/s. All constants below are
named and commented in these units so a physics student can check them.

CONTROLS (also printed to the console at startup)
------------------------------------------------------------------------
  Left-drag         orbit the camera around the system
  Right-drag        pan the camera target
  W , S             zoom in / out (dolly)
  SPACE             pause / resume
  R                 reset the simulation
  ] / [ (or UP/DOWN)  speed up / slow down simulation time
  Shift + Left-click  fire a burst of probe stars into the field at the
                      cursor (projected onto the galactic mid-plane)
  G                 toggle the reference grid
  T                 toggle orbit trails
  ESC               quit
"""

