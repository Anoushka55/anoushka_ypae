# 7. CAMERA (manual orbit / pan / zoom, built from documented ti.ui inputs only)
# =========================================================================
class OrbitCamera:
    def __init__(self):
        self.target = np.array([0.0, 0.0, 0.0])
        self.azimuth = 0.9      # radians around +z
        self.elevation = 0.55   # radians above the xy plane
        self.distance = 130.0
        self.min_dist = 8.0
        self.max_dist = 500.0
        self._last_mouse = None

    def eye(self):
        ce = np.cos(self.elevation)
        return self.target + self.distance * np.array([
            ce * np.cos(self.azimuth), ce * np.sin(self.azimuth), np.sin(self.elevation)
        ])

    def basis(self):
        """Right & up vectors of the current view, for panning."""
        forward = self.target - self.eye()
        forward = forward / (np.linalg.norm(forward) + 1e-9)
        world_up = np.array([0.0, 0.0, 1.0])
        right = np.cross(forward, world_up)
        right = right / (np.linalg.norm(right) + 1e-9)
        up = np.cross(right, forward)
        return right, up

    def handle_input(self, window):
        mouse = np.array(window.get_cursor_pos())
        if self._last_mouse is None:
            self._last_mouse = mouse
        dx, dy = mouse - self._last_mouse

        if window.is_pressed(ti.ui.LMB):
            self.azimuth -= dx * 3.2
            self.elevation = float(np.clip(self.elevation + dy * 3.2, -1.45, 1.45))
        elif window.is_pressed(ti.ui.RMB):
            right, up = self.basis()
            pan_scale = self.distance * 0.9
            self.target -= right * dx * pan_scale
            self.target -= up * dy * pan_scale

        if window.is_pressed('w'):
            self.distance *= 0.985
        if window.is_pressed('s'):
            self.distance *= 1.015
        self.distance = float(np.clip(self.distance, self.min_dist, self.max_dist))

        self._last_mouse = mouse

    def zoom(self, factor):
        self.distance = float(np.clip(self.distance * factor, self.min_dist, self.max_dist))


