# 6. SIMULATION STEP (leapfrog / velocity-Verlet: kick-drift-kick)
# =========================================================================
def physics_step(dt):
    compute_galaxy_com()
    compute_macro_accel()
    kick_macro(dt)
    drift_macro(dt)

    compute_star_accel()
    kick_stars(dt)
    drift_stars(dt)

    # second half-kick using the field at the NEW positions (proper leapfrog)
    compute_galaxy_com()
    compute_macro_accel()
    kick_macro(dt)
    compute_star_accel()
    kick_stars(dt)

    recycle_escaped_stars()
    sim_time[None] += dt


